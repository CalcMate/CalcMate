# ─── DB 업데이트 ──────────────────────────────────────────────────────────────
print("=== 섹션 보강 업데이트 ===")
results = []
for slug, add_html in APPEND.items():
    row = repo.get_by_slug(slug)
    if not row:
        print(f"[MISS] {slug}")
        continue
    existing = row.get('article_content', '') or ''
    # 기존 마지막 </p> 앞에 삽입 (관련 계산기 단락 앞에 끼워넣기)
    marker = '<h2>관련 계산기</h2>'
    if marker in existing:
        new_html = existing.replace(marker, add_html + '\n' + marker, 1)
    else:
        new_html = existing + add_html

    repo.update(row['id'], {'article_content': new_html})
    n = txt_len(new_html)
    target = "OK" if 2000 <= n <= 3000 else ("SHORT(<2000)" if n < 2000 else "LONG(>3000)")
    print(f"[OK] {slug:<36} {n}자  → {target}")
    results.append((slug, n))

print("\n=== 최종 요약 ===")
ok_count = sum(1 for _, n in results if 2000 <= n <= 3000)
print(f"목표 달성: {ok_count}/{len(results)}종")
